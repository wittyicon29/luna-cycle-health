const fs = require('fs');
const path = require('path');
const { collect, extractDetailed } = require('./check');

const NOTE = /\/\/\s*i18n-note:\s*(.*)$/;

const cell = text => String(text).replace(/\\/g, '\\\\').replace(/\|/g, '\\|').replace(/\r?\n/g, ' <br> ').trim();

// The note for a call at 1-based `line`: a trailing `// i18n-note:` on the same line, or a run of `//` comment
// lines directly above that contains one (the note runs from its marker to the end of that run).
function noteFor(lines, line) {
  const same = NOTE.exec(lines[line - 1] || '');
  if (same) return same[1].trim();
  let top = line - 1;
  while (top >= 1 && /^\s*\/\//.test(lines[top - 1])) top--;
  for (let i = top; i < line; i++) {
    const m = /^\s*\/\/\s*i18n-note:\s*(.*)$/.exec(lines[i - 1]);
    if (!m) continue;
    const parts = [m[1].trim()];
    for (let j = i + 1; j < line; j++) parts.push(lines[j - 1].replace(/^\s*\/\/\s?/, '').trim());
    return parts.join(' ').trim();
  }
  return '';
}

function gather(srcDir) {
  const entries = new Map(); // key -> { kind, text, other, locations: [], notes: [] }
  const order = [];
  collect(srcDir).forEach(file => {
    const raw = fs.readFileSync(file, 'utf8');
    const lines = raw.split('\n');
    const name = path.basename(file);
    extractDetailed(raw, name).calls.forEach(call => {
      const key = call.text;
      if (!entries.has(key)) {
        entries.set(key, { kind: call.kind, text: call.text, other: call.other, locations: [], notes: [] });
        order.push(key);
      }
      const entry = entries.get(key);
      entry.locations.push(`${name}:${call.line}`);
      const note = noteFor(lines, call.line);
      if (note && !entry.notes.includes(note)) entry.notes.push(note);
    });
  });
  return order.map(k => entries.get(k));
}

function where(locations) {
  const shown = locations.slice(0, 3).join(', ');
  return locations.length > 3 ? `${shown} +${locations.length - 3} more` : shown;
}

function buildReviewSheet({ srcDir, catalogPath }) {
  const catalog = JSON.parse(fs.readFileSync(catalogPath, 'utf8'));
  const rows = gather(srcDir).map((e, i) => {
    const entry = Object.prototype.hasOwnProperty.call(catalog, e.text) ? catalog[e.text] : undefined;
    let english;
    let hindi;
    if (e.kind === 'tn') {
      english = `${e.text} / ${e.other}`;
      const ok = entry && typeof entry === 'object' && entry.one && entry.other;
      hindi = ok ? `${entry.one} / ${entry.other}` : '—';
    } else {
      english = e.text;
      hindi = typeof entry === 'string' && entry ? entry : '—';
    }
    return { n: i + 1, english, hindi, where: where(e.locations), note: e.notes.join(' / ') };
  });

  const row = r => `| ${r.n} | ${cell(r.english)} | ${cell(r.hindi)} | ${cell(r.where)} | ${cell(r.note)} |`;
  const head = '| # | English | Hindi | Where (file:line) | Note |\n| --- | --- | --- | --- | --- |';
  const flagged = rows.filter(r => r.note);

  return [
    '# Hindi review sheet',
    '',
    '_Generated by `npm run i18n:review` from `src/i18n/catalogs/hi.json` and the source files. Do not edit by hand._',
    '',
    '## How to review',
    '',
    '- Read each row: the English on the left is what the app says, the Hindi is what a Hindi user sees. Check meaning, tone (warm, plain, respectful) and gender of verb forms.',
    '- The Note column holds the translator\'s doubts (`// i18n-note:` comments in the code). The last section lists them all in one place.',
    '- Pairs shown as `one / other` are plural forms (singular, then plural).',
    '- `{name}` markers are filled in by the app; keep them unchanged. `—` means no Hindi yet.',
    '- Glossary and wording rules: `src/i18n/HI-STYLE.md`.',
    '',
    '## How to send corrections',
    '',
    'Edit the Hindi text in `src/i18n/catalogs/hi.json` (the English sentence is the key; change only the value), or tell the developer the row number and the wording you prefer. Then run `npm run i18n:check` and `npm run i18n:review`.',
    '',
    `## All strings (${rows.length})`,
    '',
    head,
    ...rows.map(row),
    '',
    '## Flagged for the reviewer',
    '',
    flagged.length ? `${flagged.length} string(s) carry a translator note.` : 'No strings are flagged.',
    '',
    ...(flagged.length ? [head, ...flagged.map(row), ''] : []),
  ].join('\n');
}

module.exports = { buildReviewSheet };

if (require.main === module) {
  const srcDir = path.join(__dirname, '..', '..', 'src');
  const catalogPath = path.join(srcDir, 'i18n', 'catalogs', 'hi.json');
  const out = path.join(srcDir, 'i18n', 'hi-review.md');
  fs.writeFileSync(out, buildReviewSheet({ srcDir, catalogPath }));
  console.log(`wrote ${path.relative(process.cwd(), out)}`);
}
